#!/bin/bash
# Build the SITL-instance-1 models inside vincent_twin from the PX4 originals (originals untouched).
#  models/vincent_sim_base : copy of models/vincent  -> TCP 4561 / UDP 14561, base mass 1.5 -> 2.15 kg (real, with battery), + 360 ray sensor
#  models/vincent_sim      : copy of models/vincent_vision (wrapper, model name kept "vincent_vision") including vincent_sim_base
set -e
PX=$HOME/catkin_ws/src/PX4/PX4-Autopilot/Tools/simulation/gazebo-classic/sitl_gazebo-classic/models
P=$(rospack find vincent_twin)/models
mkdir -p $P/vincent_sim_base $P/vincent_sim
python3 - "$PX/vincent/vincent.sdf" "$P/vincent_sim_base/model.sdf" "$PX/vincent_vision/vincent_vision.sdf" "$P/vincent_sim/model.sdf" << 'EOF'
import sys
src, dst, wsrc, wdst = sys.argv[1:5]
s = open(src).read()
def rep(a, b):
    global s
    assert s.count(a) >= 1, "not found: " + a
    s = s.replace(a, b, 1)
rep('<mavlink_tcp_port>4560</mavlink_tcp_port>', '<mavlink_tcp_port>4561</mavlink_tcp_port>')
rep('<mavlink_udp_port>14560</mavlink_udp_port>', '<mavlink_udp_port>14561</mavlink_udp_port>')
rep('<mass>1.5</mass>', '<mass>2.15</mass>')
laser = """
      <sensor name="sim_laser" type="ray">
        <update_rate>20</update_rate>
        <visualize>false</visualize>
        <ray>
          <scan><horizontal><samples>72</samples><resolution>1</resolution>
            <min_angle>-3.14159</min_angle><max_angle>3.05433</max_angle></horizontal></scan>
          <range><min>0.30</min><max>3.0</max><resolution>0.01</resolution></range>
        </ray>
        <plugin name="sim_laser_plugin" filename="libgazebo_ros_laser.so">
          <topicName>/vincent_sim/scan</topicName>
          <frameName>vincent_sim/base_link</frameName>
        </plugin>
      </sensor>
"""
i = s.index('</link>')            # first link = base_link
s = s[:i] + laser + s[i:]
open(dst, 'w').write(s)
w = open(wsrc).read()
assert 'model://vincent</uri>' in w
w = w.replace('model://vincent</uri>', 'model://vincent_sim_base</uri>', 1)
open(wdst, 'w').write(w)
EOF
for m in vincent_sim_base vincent_sim; do
cat > $P/$m/model.config << EOF
<?xml version="1.0"?>
<model><name>$m</name><version>1.0</version><sdf version="1.5">model.sdf</sdf>
<description>Generated by make_vincent_sim.sh from the PX4 vincent / vincent_vision models (SITL instance 1)</description></model>
EOF
done
echo "--- check"; grep -n -E "mavlink_tcp_port|mavlink_udp_port|<mass>2.15|sim_laser\"|model name" $P/vincent_sim_base/model.sdf | head; grep -n -E "model name|uri" $P/vincent_sim/model.sdf
